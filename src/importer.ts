import { readdir } from 'node:fs/promises';
import path from 'node:path';
import { instructionsPath, skillsDir } from './adapters.ts';
import { TOOLS, type LinkResource, type Target, type Tool } from './manifest.ts';
import { observe } from './observe.ts';
import { collapseHome } from './paths.ts';
import { compressSelectors } from './selector.ts';

const PROFILE_DIR = new RegExp(`^\\.(${TOOLS.join('|')})(?:-([\\w-]+))?$`);

export interface Unmanaged {
  target: string;
  path: string;
}

export interface ImportResult {
  targets: Target[];
  resources: LinkResource[];
  unmanaged: Unmanaged[];
}

export async function detectTargets(home: string): Promise<Target[]> {
  const entries = await readdir(home, { withFileTypes: true });
  return entries
    .filter((entry) => entry.isDirectory())
    .flatMap((entry) => {
      const match = PROFILE_DIR.exec(entry.name);
      if (!match) return [];
      const [, tool, profile] = match;
      return [
        {
          name: entry.name.slice(1),
          tool: tool as Tool,
          dir: path.join(home, entry.name),
          tags: profile ? [profile] : [],
        },
      ];
    })
    .sort((a, b) => a.name.localeCompare(b.name));
}

export async function importFromTargets(targets: Target[]): Promise<ImportResult> {
  const found = new Map<string, { resource: Omit<LinkResource, 'to'>; targets: Target[] }>();
  const unmanaged: Unmanaged[] = [];

  const collect = (resource: Omit<LinkResource, 'to'>, target: Target) => {
    const key = `${resource.kind}\0${resource.name}\0${resource.source}`;
    const group = found.get(key) ?? { resource, targets: [] };
    group.targets.push(target);
    found.set(key, group);
  };

  for (const target of targets) {
    for (const entry of await scanSkills(target)) {
      if (entry.source) collect({ kind: 'skill', name: entry.name, source: entry.source }, target);
      else unmanaged.push({ target: target.name, path: entry.path });
    }

    const instructions = await observe(instructionsPath(target));
    if (instructions.type === 'link') {
      const name = path.basename(path.dirname(instructions.to)) || 'default';
      collect({ kind: 'instructions', name, source: instructions.to }, target);
    } else if (instructions.type === 'other') {
      unmanaged.push({ target: target.name, path: instructionsPath(target) });
    }
  }

  const resources = [...found.values()]
    .map(({ resource, targets: selected }) => ({
      ...resource,
      to: compressSelectors(selected, targets),
    }))
    .sort((a, b) => a.kind.localeCompare(b.kind) || a.name.localeCompare(b.name));

  return { targets, resources, unmanaged };
}

async function scanSkills(
  target: Target,
): Promise<{ name: string; path: string; source?: string }[]> {
  const dir = skillsDir(target);
  let names: string[];
  try {
    names = await readdir(dir);
  } catch {
    return [];
  }

  const visible = names.filter((name) => !name.startsWith('.')).sort();
  return Promise.all(
    visible.map(async (name) => {
      const entryPath = path.join(dir, name);
      const observed = await observe(entryPath);
      return observed.type === 'link'
        ? { name, path: entryPath, source: observed.to }
        : { name, path: entryPath };
    }),
  );
}

export function renderManifest(result: ImportResult, home: string): string {
  const show = (p: string) => JSON.stringify(collapseHome(p, home));
  const list = (items: string[]) => `[${items.map((item) => JSON.stringify(item)).join(', ')}]`;
  const aliases = assignSourceAliases(result.resources, home);
  const lines: string[] = [
    '# Generated by `loadout import`. Edit freely; this file is the source of truth.',
    '',
  ];

  for (const target of result.targets) {
    lines.push(
      `[targets.${target.name}]`,
      `tool = ${JSON.stringify(target.tool)}`,
      `dir = ${show(target.dir)}`,
      `tags = ${list(target.tags)}`,
      '',
    );
  }

  if (aliases.size > 0) {
    lines.push('[sources]');
    for (const [root, alias] of aliases) lines.push(`${alias} = ${show(root)}`);
    lines.push('');
  }

  for (const resource of result.resources) {
    lines.push(`[[${resource.kind}]]`, `name = ${JSON.stringify(resource.name)}`);
    const alias = resource.kind === 'skill' ? aliasFor(resource, aliases) : undefined;
    lines.push(alias ? `from = ${JSON.stringify(alias)}` : `path = ${show(resource.source)}`);
    lines.push(`to = ${list(resource.to)}`, '');
  }

  if (result.unmanaged.length > 0) {
    lines.push('# Not managed (real files/dirs, not symlinks) — left untouched:');
    for (const item of result.unmanaged) {
      lines.push(`#   ${item.target}: ${collapseHome(item.path, home)}`);
    }
  }
  return lines.join('\n').trimEnd() + '\n';
}

function aliasFor(resource: LinkResource, aliases: Map<string, string>): string | undefined {
  if (path.basename(resource.source) !== resource.name) return undefined;
  return aliases.get(path.dirname(resource.source));
}

function assignSourceAliases(resources: LinkResource[], home: string): Map<string, string> {
  const roots = new Map<string, number>();
  for (const resource of resources) {
    if (resource.kind !== 'skill' || path.basename(resource.source) !== resource.name) continue;
    const root = path.dirname(resource.source);
    roots.set(root, (roots.get(root) ?? 0) + 1);
  }

  const aliases = new Map<string, string>();
  const taken = new Set<string>();
  for (const root of [...roots.keys()].sort()) {
    const base = aliasBase(root, home);
    let alias = base;
    for (let n = 2; taken.has(alias); n++) alias = `${base}-${n}`;
    taken.add(alias);
    aliases.set(root, alias);
  }
  return aliases;
}

const UNINFORMATIVE_SEGMENT = /^(skills|\..*)$/;

function aliasBase(root: string, home: string): string {
  let current = root;
  while (
    UNINFORMATIVE_SEGMENT.test(path.basename(current)) &&
    path.dirname(current) !== home &&
    path.dirname(current) !== current
  ) {
    current = path.dirname(current);
  }
  const slug = path
    .basename(current)
    .replace(/^\./, '')
    .replace(/[^\w-]/g, '-')
    .toLowerCase();
  return slug || 'source';
}
